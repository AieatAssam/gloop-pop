#!/usr/bin/env node
// Turns docs/art/palette.json into src/render/palette.ts.
// Usage: node tools/gen-palette.mjs [--check]
//   --check  exit 1 if src/render/palette.ts is out of date (used by CI / npm run check).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'docs/art/palette.json');
const out = resolve(root, 'src/render/palette.ts');
const HEX = /^#(?:[0-9A-F]{6}|[0-9A-F]{8})$/;
const KEY = /^[a-zA-Z][a-zA-Z0-9]*$/;

const json = JSON.parse(readFileSync(src, 'utf8'));
const errors = [];

function walk(node, path) {
  if (typeof node === 'string') {
    const v = node.toUpperCase();
    if (!HEX.test(v)) errors.push(`${path.join('.')}: "${node}" is not #RRGGBB or #RRGGBBAA`);
    return JSON.stringify(v);
  }
  if (node === null || typeof node !== 'object' || Array.isArray(node)) {
    errors.push(`${path.join('.')}: expected an object or hex string`);
    return 'null';
  }
  const pad = '  '.repeat(path.length + 1);
  const lines = [];
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (!KEY.test(k)) errors.push(`${[...path, k].join('.')}: key must be camelCase identifier`);
    lines.push(`${pad}${k}: ${walk(v, [...path, k])},`);
  }
  return `{\n${lines.join('\n')}\n${'  '.repeat(path.length)}}`;
}

const body = walk(json, []);

// Every theme must define the same keys as "midnight".
const themes = json.theme ?? {};
const ref = Object.keys(themes.midnight ?? {}).sort().join(',');
for (const [name, t] of Object.entries(themes)) {
  if (Object.keys(t).sort().join(',') !== ref) errors.push(`theme.${name}: keys differ from theme.midnight`);
}
const flavourRef = Object.keys(json.flavour?.cherry ?? {}).sort().join(',');
for (const [name, f] of Object.entries(json.flavour ?? {})) {
  if (Object.keys(f).sort().join(',') !== flavourRef) errors.push(`flavour.${name}: keys differ from flavour.cherry`);
}

if (errors.length) {
  console.error('palette.json has errors:\n  ' + errors.join('\n  '));
  process.exit(1);
}

const ts = `// GENERATED by tools/gen-palette.mjs from docs/art/palette.json. Do not edit by hand.
// This is the only file in src/ allowed to contain hex colour literals.

export const PALETTE = ${body} as const;

export type Palette = typeof PALETTE;
export type FlavourKey = keyof Palette['flavour'];
export type FlavourColours = Palette['flavour'][FlavourKey];
export type ThemeKey = keyof Palette['theme'];
export type ThemeColours = Palette['theme'][ThemeKey];

/** Flavour keys in id order: index 0 is flavour id 1 (cherry). */
export const FLAVOUR_KEYS = ${JSON.stringify(Object.keys(json.flavour))} as const satisfies readonly FlavourKey[];
`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== ts) {
    console.error('src/render/palette.ts is out of date. Run: node tools/gen-palette.mjs');
    process.exit(1);
  }
  console.log('palette.ts is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, ts);
  console.log(`wrote ${out}`);
}
