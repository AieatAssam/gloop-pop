import { pathToFileURL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';

const moduleUrl = pathToFileURL(new URL('../.sim/levelGen.js', import.meta.url).pathname).href;
const { generateLevel, diagnoseLevelOne, diagnoseLevelRuns } = await import(moduleUrl);
const verify = process.argv.includes('--verify');
const write = process.argv.includes('--write');
const diagnose = process.argv.includes('--diagnose');
if (diagnose) {
  const argumentIndex = process.argv.indexOf('--diagnose');
  const level = Number(process.argv[argumentIndex + 1] ?? 1);
  const seedIndex = Number(process.argv[argumentIndex + 2] ?? 0);
  console.log(`Level ${level}, seed ${seedIndex}: 12 runs against calibrated goal targets`);
  for (const line of level === 1 && seedIndex === 0 ? diagnoseLevelOne() : diagnoseLevelRuns(level, seedIndex)) console.log(line);
  process.exit(0);
}

const startedAt = performance.now();
const levels = [];
for (let n = 1; n <= 120; n += 1) {
  levels.push(generateLevel(n));
  if (n % 10 === 0) console.log(`validated ${n}/120`);
}
const source = `// GENERATED by tools/gen-levels.mjs — do not edit\nimport type { LevelDef } from './levels';\nexport const LEVELS: readonly LevelDef[] = ${JSON.stringify(levels)};\n`;
const tableUrl = new URL('../src/core/levels.data.ts', import.meta.url);
if (write) await writeFile(tableUrl, source);
if (verify) {
  const existing = await readFile(tableUrl, 'utf8');
  if (existing !== source) throw new Error('Generated levels differ from src/core/levels.data.ts; run npm run levels -- --write');
}
printSummary(levels);
console.log(`Adventure level ${verify ? 'verification' : 'generation'} completed in ${(performance.now() - startedAt).toFixed(0)} ms`);

function printSummary(definitions) {
  console.log('Chapter/band    mean wins/12    mean moves    mean s3');
  for (let chapter = 1; chapter <= 6; chapter += 1) {
    for (const band of ['easy', 'normal', 'hard']) {
      const group = definitions.filter((def) => Math.ceil(def.n / 20) === chapter && bandFor(def.n) === band);
      if (group.length === 0) continue;
      console.log(`Ch ${chapter} ${band.padEnd(6)} ${mean(group.map((def) => def.wins)).toFixed(2).padStart(8)} ${mean(group.map((def) => def.moves)).toFixed(2).padStart(13)} ${mean(group.map((def) => def.s3)).toFixed(2).padStart(12)}`);
    }
  }
  const retried = definitions.filter((def) => def.s > 0).map((def) => `${def.n}:${def.s}`);
  console.log(`Seeds needing more than one try: ${retried.length ? retried.join(', ') : 'none'}`);
}

function mean(values) { return values.reduce((sum, value) => sum + value, 0) / values.length; }
function bandFor(level) {
  const position = (level - 1) % 20 + 1;
  if (level <= 3) return 'intro';
  if ([1, 6, 11, 16].includes(position)) return 'easy';
  if ([5, 10, 15, 20].includes(position)) return 'hard';
  return 'normal';
}
