import { pathToFileURL } from 'node:url';
import { writeFile } from 'node:fs/promises';
const moduleUrl=pathToFileURL(new URL('../.sim/levelGen.js',import.meta.url).pathname).href;
const {generateLevel}=await import(moduleUrl);
const verify=process.argv.includes('--verify');const write=process.argv.includes('--write');
const start=performance.now();const levels=[];
for(let n=1;n<=120;n++){
  if(verify){const old=await import('../src/core/levels.data.ts').catch(()=>null);void old;}
  levels.push(generateLevel(n));
  if(n%10===0)console.log(`validated ${n}/120`);
}
const source=`// GENERATED by tools/gen-levels.mjs — do not edit\nimport type { LevelDef } from './levels';\nexport const LEVELS: readonly LevelDef[] = ${JSON.stringify(levels)};\n`;
if(write)await writeFile(new URL('../src/core/levels.data.ts',import.meta.url),source);
const elapsed=performance.now()-start;
console.log(`Adventure level generation ${verify?'verified':'complete'} in ${elapsed.toFixed(0)} ms`);
console.log('Chapter means are recorded in docs/balance-log.md after validation.');
